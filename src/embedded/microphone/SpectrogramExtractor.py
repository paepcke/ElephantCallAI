import numpy as np
from matplotlib import mlab as ml


class SpectrogramExtractor:
    """
    An object that encapsulates STFT settings to provide a simple interface for
    performing a frequency transform.
    """

    nfft: int  # Window size used for creating spectrograms
    hop: int  # Hop size used for creating spectrograms
    max_freq: int  # Determines the maximum frequency band we keep
    sampling_freq: int  # The frequency at which the data is sampled
    pad_to: int  # Determines the padded window size that we want to give a particular grid spacing (e.g., 1.95hz)

    """
    Here's how these parameters affect spectrogram shape:

    A generated spectrogram is a (T, F) array where T is the number of time steps and F is the number of frequency buckets.
    It's generated from a sequence of audio samples with length S.

    T = max(1, (S - nfft)//hop)

    if max_freq >= sampling_freq/2:
        if pad_to is not None:
            F = pad_to//2 + 1
        else:
            F = nfft//2 + 1
    else:
        if pad_to is not None:
            nonzero_freqs_kept = max_freq/(sampling_freq/2) * (pad_to//2)
        else:
            nonzero_freqs_kept = max_freq/(sampling_freq/2) * (nfft//2)
        F = floor(nonzero_freqs_kept) + 1
    """

    def __init__(self, nfft: int = 4096, hop: int = 800,
                 max_freq: int = 150, sampling_freq: int = 8000, pad_to: int = 4096):
        self.nfft = nfft
        self.hop = hop
        self.max_freq = max_freq
        self.sampling_freq = sampling_freq
        self.pad_to = pad_to

    def extract_spectrogram(self, time_amplitudes: np.ndarray) -> np.ndarray:
        """
        returns a matrix where each row corresponds to a time step and each column corresonds to a frequency;
        longer inputs result in a matrix with more rows.

        :param time_amplitudes: a signal in the time domain
        :return: a spectrogram matrix of size (TxF), where T is the number of time slices and F is the number of frequencies
        """

        [spectrum, freqs, t] = ml.specgram(time_amplitudes,
                                           NFFT=self.nfft, Fs=self.sampling_freq,
                                           noverlap=(self.nfft - self.hop), window=ml.window_hanning,
                                           pad_to=self.pad_to)
        # Cut out the high frequencies that are not of interest
        spectrum = spectrum[(freqs <= self.max_freq)]
        return spectrum.T

    def num_freq_bins(self):
        # returns the number of frequency bins that all spectrograms generated by this extractor will have
        if self.max_freq >= self.sampling_freq // 2:
            # max_freq effectively does nothing
            if self.pad_to is not None:
                freq_bins = self.pad_to // 2 + 1
            else:
                freq_bins = self.nfft // 2 + 1
        else:
            if self.pad_to is not None:
                nonzero_freqs_kept = self.max_freq / (self.sampling_freq / 2) * (self.pad_to // 2)
            else:
                nonzero_freqs_kept = self.max_freq / (self.sampling_freq / 2) * (self.nfft // 2)
            freq_bins = int(nonzero_freqs_kept) + 1
        return freq_bins
